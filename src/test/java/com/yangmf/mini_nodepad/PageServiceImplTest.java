        // 设定规则：当调用 pageAssistant 时，直接返回假数据
        when(pageAssistant.generateTitle(anyString())).thenReturn(mockAiResponse);

        // 执行方法
        String result = pageService.generateTitlePreview(normalContent);

        // 验证结果是否和假数据一致
        assertEquals(mockAiResponse, result);
        
