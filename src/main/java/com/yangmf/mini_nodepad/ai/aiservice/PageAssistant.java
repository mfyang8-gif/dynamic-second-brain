package com.yangmf.mini_nodepad.ai.aiservice;

import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;

public interface PageAssistant {

    /**
     * AI 生成摘要：受 @Size(max = 500) 约束
     * 核心策略：限制字数，强制剥离无关废话，聚焦核心骨架
     */

    @SystemMessage("""
请对以下正文内容进行专业、严谨的摘要总结。

【执行规则】：
1. 强制结构约束：摘要必须具有清晰的层次与脉络，请参考（但不限于）以下句式模板组织你的输出：
   “本文从 [维度A]、[维度B]、[维度C] 等几个方面讲述了 [核心主旨]。文章自上而下，从 [核心概念/底层逻辑] 的剖析，到 [具体场景/代表性例子] 的应用，详细阐述了 [关键结论或操作指南]。”
2. 丰富细节与案例：为了保证摘要内容的饱满度，切忌只做高度抽象。必须在摘要中融入文中的核心策略步骤或最具代表性的应用场景（如职场、感情等），让摘要言之有物。
3. 严格字数限制：摘要字数严格控制在 100 到 250 字之间。既要展开细节解决内容过短的问题，又要避免冗长，绝对不可超过500字极限。
4. 纯净输出：严禁输出任何废话前缀（如“好的”、“本文摘要如下：”等），必须直接输出按照上述结构组织好的摘要正文。
5.严禁带（如 ### 标题、- 列表、**加粗**）这种markdown格式，直接给纯文本
正文内容：
{{it}}
""")
    String generateSummary(String text);

    /**
     * AI 生成标题：受 @Size(max = 200) 约束
     * 核心策略：要求极致简短（通常书签标题30个字以内最好），禁止特殊符号
     */

    @SystemMessage("""
    请根据以下用户提供的正文内容，生成一个高度精炼的标题。
    
    【执行规则】：
    1. 极致简炼：标题字数建议在 10 到 30 个字符之间（系统硬性上限为200字符，严禁超标）。
    2. 一语中的：用最专业的词汇，准确概括文本的最核心特征。
    3. 纯净输出：
       - 绝对禁止包含说明性废话（如"标题："、"生成结果："等）。
       - 绝对禁止在标题外层添加任何引号（""、''）或书名号（《》）。
       - 仅需返回纯文本内容本身。
       
    正文内容：
    {{it}}
    """)
    String generateTitle(String text);
}