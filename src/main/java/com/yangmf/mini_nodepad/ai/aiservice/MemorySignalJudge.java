package com.yangmf.mini_nodepad.ai.aiservice;

import com.yangmf.mini_nodepad.pojo.dto.MemorySignalVerdict;
import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;
import dev.langchain4j.service.V;

/**
 * 实质判定器（B1 发现层的守门人）。
 *
 * <p>职责：判断<b>一个用户的对话轮次</b>是否包含「值得沉淀为长期记忆的用户属性 / 事实」。
 * 通过的轮次才会被投递给 Graphiti；判否的轮次进入审计表（终态隔离）。
 *
 * <p>为什么需要它：Graphiti 的 {@code add_episode} 会对每一条投进来的消息跑一次 LLM 抽取
 * （实测 15~45s，且按 token 计费）。如果「你好」「帮我改个变量名」这类纯操作指令也投进去，
 * 结果是：① 消费吞吐被无意义地占满（单协程 2 条/分钟），② 图谱被噪音实体污染，
 * ③ 召回时噪音挤掉真记忆。判定器就是这道闸。
 *
 * <p>三个设计约束：
 * <ol>
 *   <li><b>判否必须落审计表</b>（{@code reason = JUDGE_REJECTED}）——
 *       这既是「永不投递」的权威标记，也是 P7 层 4 抽样（查漏拦）的唯一数据来源。</li>
 *   <li><b>它是可关的</b>（{@code graphiti.write.judge-enabled}）：关闭时全部走规则快通道 ——
 *       「全量投递」比「误拦真记忆」更安全，因为前者的代价是成本与噪音，后者是记忆缺失。</li>
 *   <li><b>它只回答二值问题</b>，不负责抽取内容 —— 抽取是 Graphiti 的职责，
 *       在此处做抽取等于把「写入链路」变成「提取链路」，会让改口裁决失去原始时间锚点。</li>
 * </ol>
 *
 * <p>⚠️ 判定器<b>不</b>接收助手回答：AI 回答中的客串假设句（「假设你现在用 Go……」）
 * 会诱导抽取器产生自我强化幻觉 —— 这是既有链路的既有裁决，继续沿用。
 */
public interface MemorySignalJudge {

    @SystemMessage("""
            你是一个长期记忆的守门人。你的唯一任务是判断：用户这一句话里，是否包含
            「关于用户本人的、值得跨会话长期记住的」信息。

            判定为 true（值得记住）的情形：
            - 个人属性与关系：姓名、职业、家庭关系、所在地；
            - 稳定的偏好与口味：喜欢/讨厌什么技术、语言、格式、风格；
            - 习惯与工作方式：常用的工具链、代码规范、协作方式；
            - 明确的禁忌与硬约束：过敏、疾病、不能吃/不能做的事、合规红线；
            - 长期目标与计划：正在学的方向、要完成的项目。

            判定为 false（不值得记住）的情形：
            - 一次性的操作指令：「帮我改个变量名」「把这个函数拆开」「再写一版」；
            - 纯信息查询：「什么是 RAG」「这个报错什么意思」「今天几号」；
            - 寒暄与情绪：「你好」「谢谢」「太慢了」「好的」；
            - 与用户本人无关的内容：粘贴的第三方代码、别人的话、无主语的片段；
            - 你无法确定它是在描述用户本人（而非举例、假设、引用）时。

            判定原则：
            1. 稳定性优先 —— 只记「下次对话仍然成立」的信息，临时的、当下的都不算；
            2. 宁缺毋滥只适用于「不确定时」，但不要把明确的偏好/禁忌误判为闲聊；
            3. 只依据这一句话本身判断，不要脑补上下文里不存在的信息。

            输出格式要求：只输出 JSON 对象，形如
            {"shouldRemember": true, "reason": "用户在描述自己的过敏史"}
            或
            {"shouldRemember": false, "reason": "一次性的代码修改指令"}
            除 JSON 外绝不输出任何解释文字。
            """)
    @UserMessage("""
            用户这一轮的原话：
            {{turn}}
            """)
    MemorySignalVerdict judge(@V("turn") String turn);
}
